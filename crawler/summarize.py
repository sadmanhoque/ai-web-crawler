"""
summarize.py — short (<=150 word) page summaries for the search index.

Open-weight only: generated by a local Ollama model on the minikube host
(same OLLAMA_URL / SUMMARY_MODEL env names the ai-web-search backend uses
for its /search/summary answer card, so one model setting covers both).
No API keys, nothing leaves the infra.

If Ollama is unreachable or returns nothing, falls back to an extractive
first-1200-chars summary — a crawl must never fail on a model outage.
"""

import os

import requests

_TIMEOUT_S = 60

PROMPT = (
    "Summarize this web page in at most 150 words for a search index. Keep key "
    "facts, names, numbers and terminology. No preamble.\n\n"
    "Title: {title}\n\n{text}"
)


def summarize(title: str, text: str) -> str:
    text = text[:20000]
    url = os.getenv("OLLAMA_URL", "http://host.minikube.internal:11434")
    try:
        resp = requests.post(
            f"{url.rstrip('/')}/api/generate",
            json={
                "model":   os.getenv("SUMMARY_MODEL", "llama3.2:3b"),
                "prompt":  PROMPT.format(title=title, text=text),
                "stream":  False,
                "options": {"temperature": 0.2, "num_predict": 400},
            },
            timeout=_TIMEOUT_S,
        )
        resp.raise_for_status()
        out = resp.json().get("response", "").strip()
        return out or text[:1200]
    except requests.RequestException:
        return text[:1200]
